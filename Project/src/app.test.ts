const config: Config = { port: 0, demo: true, production: false, origin: 'http://localhost:5173', telegramGroups: ['-1001'], botInternalSecret: 'app-tests-service-secret-'.repeat(2), adminTelegramIds: [], sessionTtlMs: 60_000, demoUserId: 'user-1', demoAccessLevel: 'admin' };
test('shared pages coalesce reads, negotiate gzip, invalidate on writes and respect live access', async t => {
  const seed = createSeed();
  const member = seed.users[1]!;
  member.role = 'member';
  member.access = accessForLevel('member', 'telegram');
  const token = 'a'.repeat(64);
  seed.telegramUsers['123456'] = member.id;
  seed.sessions[hashToken(token)] = { userId: member.id, source: 'telegram', expiresAt: new Date(Date.now() + 60_000).toISOString() };
  seed.tags.push(...Array.from({ length: 80 }, (_, i) => ({ id: 'cache-' + i, name: 'Тестовый тег ' + i })));
  const draft = { ...seed.entities[0]!, id: 'private-team', type: 'teams' as const, status: 'draft' };
  seed.entities.push(draft);
  class CountingRepository extends MemoryRepository {
    reads = 0;
    readPage<T>(_page: CommunityPage, fn: (state: DatabaseState) => T) { this.reads++; return this.read(fn); }
  }
  const repo = new CountingRepository(seed);
  const { app } = createApp(repo, { ...config, telegramGroupMembershipRequired: false });
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => { server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api`;
  const login = await fetch(base + '/auth/demo', { method: 'POST', headers: { origin: config.origin, 'content-type': 'application/json' }, body: '{}' });
  const admin = login.headers.getSetCookie()[0]!.split(';')[0]!;
  const cookie = 'klan_session=' + token;
  const get = (path: string, session: string, encoding = 'identity') => fetch(base + path, { headers: { cookie: session, 'accept-encoding': encoding } });
  const [plain, zipped] = await Promise.all([get('/tags', cookie), get('/tags', cookie, 'gzip')]);
  assert.equal(repo.reads, 1);
  assert.equal(plain.headers.get('content-encoding'), null);
  assert.equal(zipped.headers.get('content-encoding'), 'gzip');
  assert.match(zipped.headers.get('vary')!, /Accept-Encoding/i);
  assert.equal(zipped.headers.get('cache-control'), 'no-store');
  const tags = await plain.json();
  assert.deepEqual(tags, await zipped.json());
  const brotli = await get('/tags', cookie, 'br');
  assert.equal(brotli.headers.get('content-encoding'), 'br');
  assert.deepEqual(tags, await brotli.json());
  const challenge = seed.entities.find(entity => entity.type === 'challenges')!;
  await repo.write(state => { state.entities.push({ ...challenge, publicId: undefined, id: 'draft-challenge', status: 'draft' }); });
  const detail = (id: string, session: string) => get('/challenges/' + id + '?view=detail', session);
  assert.equal((await (await detail('draft-challenge', admin)).json()).data.id, 'draft-challenge');
  assert.equal((await detail('draft-challenge', cookie)).status, 404);
  assert.equal((await (await detail(challenge.id, admin)).json()).data.id, challenge.id);
  const teamIds = async (session: string) => (await (await get('/stats', session)).json()).data.teams.map((team: {id: string}) => team.id);
  const draftId = await repo.read(s => s.entities.find(e => e.id === draft.id)!.publicId);
  assert.equal((await get(`/teams/${draftId}?view=detail`,cookie)).status,404);
  const visibleCards = (await (await get('/teams?view=cards&limit=30',cookie)).json()).data;
  assert.ok(visibleCards.length && visibleCards.every((row: {id:string;publicId:number;participants?:unknown;participantCount:number}) =>
    row.id !== draft.id && row.publicId > 0 && Number.isInteger(row.participantCount) && row.participants === undefined));
  assert.ok((await teamIds(admin)).includes(draft.id));
  assert.ok(!(await teamIds(cookie)).includes(draft.id));
  await repo.write(state => { state.tags.push({ id: 'updated', name: 'Добавлен' }); });
  assert.ok((await (await get('/tags', cookie)).json()).data.some((tag: {id: string}) => tag.id === 'updated'));
  await repo.write(state => { delete state.sessions[hashToken(token)]; });
  assert.equal((await get('/tags', cookie)).status, 401);
});
test('API auth, CSRF, catalog writes, profile, admin CRUD, errors, export and filters', async t => {
  const repo = new MemoryRepository(createSeed());
  const activities: Activity[] = [];
  const { app } = createApp(repo, config, message => { if (message.type === 'activity') activities.push(message.data); }, {
    telegramRequest: async <T>() => ({ status: 'member' }) as T,
  });
  const server = createServer(app).listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); });
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api`;
  assert.equal((await fetch(`${base}/users`)).status, 401);
  assert.equal((await fetch(`${base}/auth/demo`, { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://evil.example' }, body: '{}' })).status, 403);
  const login = await fetch(`${base}/auth/demo`, { method: 'POST', headers: { origin: config.origin, 'content-type': 'application/json' }, body: '{}' });
  assert.equal(login.status, 200);
  const cookie = login.headers.getSetCookie()[0]!.split(';')[0]!;
  const headers = { cookie, origin: config.origin, 'content-type': 'application/json' };
  const members = await fetch(`${base}/users?limit=5&page=2&sort=name`, { headers });
  assert.equal(members.status, 200); const memberBody = await members.json(); assert.equal(memberBody.meta.total, 24); assert.equal(memberBody.data.length, 5);
  assert.equal((await fetch(`${base}/users?limit=oops`, { headers })).status, 400);
  const tags = await fetch(`${base}/tags`, { method: 'POST', headers, body: JSON.stringify({ name: 'Тестовый интерес' }) }); assert.equal(tags.status, 201);
  const tag = (await tags.json()).data;
  const profile = await fetch(`${base}/users/me`, { method: 'PATCH', headers, body: JSON.stringify({ bio: 'Обновлено', tags: [tag] }) }); assert.equal(profile.status, 200);
  assert.equal((await profile.json()).data.tags[0].name, 'Тестовый интерес');
  assert.equal((await fetch(`${base}/users/me`, { method: 'PATCH', headers, body: JSON.stringify({ role: 'admin' }) })).status, 400);
  const created = await fetch(`${base}/news`, { method: 'POST', headers, body: JSON.stringify({ title: 'Новость', description: 'Описание', category: 'community' }) }); assert.equal(created.status, 201);
  const entity = (await created.json()).data;
  assert.equal((await fetch(`${base}/news/${entity.id}`, { headers })).status, 200);
  assert.equal((await fetch(`${base}/news/${entity.id}`, { method: 'DELETE', headers })).status, 200);
  assert.equal((await fetch(`${base}/news/${entity.id}`, { headers })).status, 404);
  const draftResponse = await fetch(`${base}/news`, { method: 'POST', headers, body: JSON.stringify({ title: 'Закрытый черновик', description: 'Не публиковать', status: 'draft' }) });
  const draft = (await draftResponse.json()).data;
  const memberToken = 'b'.repeat(64);
  await repo.write(state => { state.telegramUsers['12345'] = 'user-2'; state.sessions[hashToken(memberToken)] = { userId: 'user-2', expiresAt: new Date(Date.now() + 60000).toISOString(), source: 'telegram' }; });
  const memberHeaders = { ...headers, cookie: `klan_session=${memberToken}` };
  assert.equal((await fetch(`${base}/news/${draft.id}`, { headers: memberHeaders })).status, 404);
  const memberNews = await (await fetch(`${base}/news`, { headers: memberHeaders })).json();
  assert.ok(!memberNews.data.some((item: { id: string }) => item.id === draft.id));
  assert.ok(!activities.some(activity => activity.target?.path === `/news/${draft.id}`));
  assert.equal((await fetch(`${base}/news/${draft.id}`, { method: 'DELETE', headers })).status, 200);
  const memberActivity = await (await fetch(`${base}/activity`, { headers: memberHeaders })).json();
  assert.ok(!memberActivity.data.some((activity: Activity) => activity.target?.path === `/news/${draft.id}`));
  const memberDashboard = await (await fetch(`${base}/dashboard`, { headers: memberHeaders })).json();
  assert.ok(!memberDashboard.data.activity.some((activity: Activity) => activity.target?.path === `/news/${draft.id}`));
  const exported = await (await fetch(`${base}/users/me/export`, { headers })).json(); assert.equal(exported.data.profile.bio, 'Обновлено'); assert.equal(exported.data.profile.role, undefined);
  assert.equal((await fetch(`${base}/users/me/import`, { method: 'POST', headers, body: JSON.stringify({ profile: { bio: 'Импорт', role: 'admin' } }) })).status, 400);
  const geography = await (await fetch(`${base}/geography`, { headers })).json(); assert.equal(geography.data.reduce((sum: number, city: { count: number }) => sum + city.count, 0), 24);
  assert.equal((await fetch(`${base}/dashboard`, { headers })).status, 200);
  assert.equal((await fetch(`${base}/stats`, { headers })).status, 200);
  await fetch(`${base}/auth/logout`, { method: 'POST', headers, body: '{}' });
  assert.equal((await fetch(`${base}/users`, { headers })).status, 401);
});

test('Numeric profile deletion preserves ownership checks and the public ID high-water mark', async t => {
  const initial = createSeed();
  initial.users[0]!.publicId = 1;
  initial.users[1]!.publicId = 2;
  initial.userPublicIds.highWater = 20;
  const repo = new MemoryRepository(initial);
  const { app } = createApp(repo, config);
  const server = createServer(app).listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); });
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api`;
  const login = await fetch(`${base}/auth/demo`, { method: 'POST', headers: { origin: config.origin, 'content-type': 'application/json' }, body: '{}' });
  assert.equal(login.status, 200);
  const headers = { cookie: login.headers.getSetCookie()[0]!.split(';')[0]!, origin: config.origin, 'content-type': 'application/json' };
  assert.equal((await fetch(`${base}/users/1`, { method: 'DELETE', headers })).status, 409);
  assert.equal((await fetch(`${base}/users/2`, { method: 'DELETE', headers })).status, 200);
  const state = await repo.read(value => value);
  assert.ok(state.users.some(user => user.id === 'user-1'));
  assert.ok(!state.users.some(user => user.id === 'user-2'));
  assert.equal(state.userPublicIds.highWater, 20 + initial.users.length - 2);
});

test('geography omits missing coordinates and empty city names without dropping users from totals', async t => {
  const initial = createSeed();
  initial.users = initial.users.slice(0, 3);
  initial.entities = [];
  initial.users[0]!.location = { city: '  ', country: '', lat: 0, lng: 0 };
  initial.users[1]!.location = { city: 'Город без координат', country: '', lat: null, lng: null };
  initial.users[2]!.location = { city: 'Москва', country: 'Россия', lat: 55.75, lng: 37.6 };
  const { app } = createApp(new MemoryRepository(initial), config);
  const server = createServer(app).listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); });
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api`;
  const login = await fetch(`${base}/auth/demo`, { method: 'POST', headers: { origin: config.origin, 'content-type': 'application/json' }, body: '{}' });
  assert.equal(login.status, 200);
  const headers = { cookie: login.headers.getSetCookie()[0]!.split(';')[0]! };
  const geography = await (await fetch(`${base}/geography`, { headers })).json();
  assert.equal(geography.data.length, 1);
  assert.equal(geography.data[0].city, 'Москва');
  assert.equal(geography.data[0].count, 1);
  const dashboard = await (await fetch(`${base}/dashboard`, { headers })).json();
  assert.equal(dashboard.data.stats.users, 3);
  assert.equal(dashboard.data.stats.cities, 1);
  const stats = await (await fetch(`${base}/stats`, { headers })).json();
  assert.equal(stats.data.users, 3);
  assert.equal(stats.data.cities.length, 2);
  assert.ok(stats.data.cities.every((city: { name: string }) => city.name.trim()));
  const users = await (await fetch(`${base}/users`, { headers })).json();
  assert.equal(users.meta.total, 3);
});
